import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = new URL('../../', import.meta.url);
const tokens = JSON.parse(
  await readFile(new URL('apps/desktop/src/shared/theme/config/tesseraTokens.json', root), 'utf8'),
);
const paletteAliases = {
  canvas: 'canvas',
  bg: 'canvas',
  surface: 'panel',
  'surface-raised': 'raised',
  'surface-hover': 'hover',
  'surface-active': 'pressed',
  border: 'border',
  'border-strong': 'borderStrong',
  text: 'text',
  muted: 'textSecondary',
  subtle: 'textMuted',
  disabled: 'borderStrong',
  primary: 'primary',
  focus: 'primary',
  'primary-action': 'primary',
  'primary-action-hover': 'textSecondary',
  'primary-action-pressed': 'textMuted',
  'primary-foreground': 'primaryText',
  'primary-soft': 'panel',
  'primary-soft-hover': 'hover',
  secondary: 'raised',
  'secondary-foreground': 'text',
  accent: 'accent',
  'accent-foreground': 'text',
  'accent-soft': 'raised',
  success: 'primary',
  'success-foreground': 'text',
  'success-soft': 'raised',
  warning: 'primary',
  'warning-foreground': 'text',
  'warning-soft': 'raised',
  danger: 'primary',
  'danger-action': 'panel',
  'danger-action-hover': 'hover',
  'danger-foreground': 'text',
  'danger-soft': 'raised',
};
const aliases = (palette) =>
  Object.entries(paletteAliases).map(([key, name]) => `  --color-${key}: ${palette[name]};`);
const scoped = (name, palette) =>
  [
    `${name === 'dark' ? ':root,\n' : ''}[data-color-theme='${name}'] {`,
    `  color-scheme: ${name};`,
    ...Object.entries(palette).map(([key, value]) => `  --ts-color-${key}: ${value};`),
    ...aliases(palette),
    `  --color-overlay: color-mix(in srgb, ${palette.canvas} 80%, transparent);`,
    '  --color-shadow-tint: rgb(0 0 0 / 20%);',
    ...Object.entries({
      'focus-ring': 80,
      selection: 22,
      'signal-ring': 30,
      'signal-glow': 8,
      'signal-glow-strong': 16,
    }).map(
      ([key, percent]) =>
        `  --${key}-color: color-mix(in srgb, ${palette.primary} ${percent}%, transparent);`,
    ),
    '}',
  ].join('\n');
const css = await format(
  [
    '/* Generated by task fe:theme:generate from the Tessera light/dark token snapshot. */',
    '@theme {',
    ...aliases(tokens.themes.dark),
    `  --font-sans: ${tokens.type.ui};`,
    `  --font-mono: ${tokens.type.technical};`,
    `  --font-display: ${tokens.type.display};`,
    ...['xs', 'sm', 'md', 'lg', 'xl', '2xl', '3xl', '4xl'].map(
      (size) => `  --radius-${size}: ${tokens.shape.cornerRadius}px;`,
    ),
    '  --shadow-sm: none;',
    '  --shadow-md: none;',
    '  --shadow-lg: none;',
    '}',
    ':root {',
    ...Object.entries(tokens.space).map(([key, value]) => `  --ts-space-${key}: ${value}px;`),
    `  --ts-shape-cornerRadius: ${tokens.shape.cornerRadius}px;`,
    `  --ts-shape-borderWidth: ${tokens.shape.borderWidth}px;`,
    `  --ts-type-uiDefault-size: ${tokens.type.uiDefault.size}px;`,
    '}',
    ...Object.entries(tokens.themes).map(([name, palette]) => scoped(name, palette)),
    '',
  ].join('\n'),
  { parser: 'css', singleQuote: true },
);
const target = new URL('apps/desktop/src/app/styles/tessera-tokens.css', root);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== css)
    throw new Error('Tessera CSS differs from its token source; run task fe:theme:generate');
} else await writeFile(target, css);
process.stdout.write(
  `Tessera light/dark tokens ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${fileURLToPath(target)}\n`,
);
